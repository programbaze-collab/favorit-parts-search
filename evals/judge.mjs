// LLM-as-a-judge: вторая модель оценивает то, что не проверить регулярным выражением, —
// понятность и полезность ответа для покупателя.
import { chat } from './agent.mjs'

export const PASS_SCORE = 4

const RUBRIC = `Ты проверяешь ответы Telegram-бота магазина автозапчастей. Бот ищет детали и аналоги по артикулу через API поставщика.

Оцени последний ответ бота по шкале от 1 до 5:
5 — полностью решает задачу пользователя: понятно, коротко, есть всё нужное для решения о покупке (производитель, номер, цена, наличие, срок), или правильно уточняет, если запрос неоднозначен.
4 — решает задачу, есть мелкие недочёты: лишние слова, неудачный порядок.
3 — частично решает задачу: чего-то важного не хватает или ответ трудно читать.
2 — почти не помогает пользователю.
1 — не отвечает на вопрос, вводит в заблуждение или противоречит данным инструментов.

Правила бота, которые нужно учитывать:
- цены, остатки и сроки — только из данных инструментов;
- если по артикулу несколько производителей, а нужный не назван, бот перечисляет их и спрашивает. Если пользователь назвал производителя (в любом регистре, в любом месте сообщения), уточнять не нужно — бот сразу отвечает про этого производителя, и это правильно;
- если артикула нет, бот просит его прислать;
- если инструмент вернул ошибку, бот объясняет её простыми словами;
- аналогов показывает не больше пяти, самые дешёвые в наличии;
- пишет по-русски простым текстом без Markdown.

Поля в данных инструментов: stock — общий остаток по всем складам, minPrice — минимальная цена, bestWarehouse — самый дешёвый склад с его собственным остатком.

Сверяй факты в ответе с данными инструментов. Ответь JSON: {"score": число от 1 до 5, "reason": "одно-два предложения по-русски"}.`

// Ответы инструментов бывают длинными — судье хватит начала.
const clip = (text, max = 3000) => (text.length > max ? `${text.slice(0, max)}…` : text)

export async function judge({ turns, answers, toolCalls, apiKey }) {
  const dialog = turns
    .map((turn, i) => `Пользователь: ${turn}\nБот: ${answers[i] ?? ''}`)
    .join('\n\n')
  const tools = toolCalls.length
    ? toolCalls.map((call) => `${call.name}(${JSON.stringify(call.args)}) →\n${clip(call.output)}`).join('\n\n')
    : 'инструменты не вызывались'

  const message = await chat(
    [
      { role: 'system', content: RUBRIC },
      { role: 'user', content: `Диалог:\n${dialog}\n\nДанные инструментов:\n${tools}` },
    ],
    { apiKey, temperature: 0, json: true },
  )
  const { score, reason } = JSON.parse(message.content)
  return { score: Number(score), reason: String(reason) }
}
